#!/usr/bin/env python3
"""
Build the portal's favicons from the Terminal İstanbul block symbol.

The symbol is the left part of public/assets/brand/terminal-istanbul.svg (x 0–80.4,
y 0–160.9 in that file's units): two blue and two red blocks. It is placed on a white rounded
tile so the dark blue still shows on a dark browser tab.

Writes, into public/:
  favicon.svg           the vector icon modern browsers use
  favicon.ico           16, 32 and 48 px, for browsers that ignore SVG icons
  apple-touch-icon.png  180 px, for iOS home-screen bookmarks (iOS rounds the corners itself)
src/index.html links all three.

Needs Pillow (pip install pillow). Run from the repo root:  python3 tools/favicon/build.py
"""
from pathlib import Path

from PIL import Image, ImageDraw

PUBLIC = Path(__file__).resolve().parents[2] / "public"

RED = "#ED1C2C"
BLUE = "#2B3B8E"
TILE = "#FFFFFF"

# Symbol polygons in the logo's own units, painted in this order (blue lies over red, as in
# the logo file).
SYMBOL_H = 160.9
SYMBOL_W = 80.4
SHAPES = [
    (RED, [(40.2, 40.2), (70.4, 40.2), (80.4, 50.2), (80.4, 80.4), (40.2, 80.4)]),
    (RED, [(0, 120.7), (80.4, 120.7), (80.4, 160.9), (0, 160.9)]),
    (BLUE, [(0, 0), (30.2, 0), (40.2, 10), (40.2, 40.2), (0, 40.2)]),
    (BLUE, [(0, 80.4), (40.2, 80.4), (40.2, 160.8), (0, 160.8)]),
]

# Tile layout in a 64-unit square.
TILE_SIZE = 64
TILE_RADIUS = 12
MARK_H = 50  # symbol height on the tile
SCALE = MARK_H / SYMBOL_H
OFFSET_X = (TILE_SIZE - SYMBOL_W * SCALE) / 2
OFFSET_Y = (TILE_SIZE - MARK_H) / 2


def svg() -> str:
    paths = "\n".join(
        f'    <path fill="{color}" d="M{" L".join(f"{x:g},{y:g}" for x, y in pts)}Z"/>'
        for color, pts in SHAPES
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {TILE_SIZE} {TILE_SIZE}">\n'
        f"  <!-- Generated by tools/favicon/build.py; edit that, not this file. -->\n"
        f'  <rect width="{TILE_SIZE}" height="{TILE_SIZE}" rx="{TILE_RADIUS}" fill="{TILE}"/>\n'
        f'  <g transform="translate({OFFSET_X:.3f} {OFFSET_Y:.3f}) scale({SCALE:.5f})">\n'
        f"{paths}\n"
        f"  </g>\n"
        f"</svg>\n"
    )


def raster(size: int, rounded: bool) -> Image.Image:
    """Draw at 16x the size, then shrink, for smooth edges."""
    big = size * 16
    k = big / TILE_SIZE
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if rounded:
        d.rounded_rectangle((0, 0, big - 1, big - 1), radius=TILE_RADIUS * k, fill=TILE)
    else:
        d.rectangle((0, 0, big - 1, big - 1), fill=TILE)
    for color, pts in SHAPES:
        d.polygon([((OFFSET_X + x * SCALE) * k, (OFFSET_Y + y * SCALE) * k) for x, y in pts], fill=color)
    return img.resize((size, size), Image.LANCZOS)


def main() -> None:
    (PUBLIC / "favicon.svg").write_text(svg(), encoding="utf-8")

    ico = [raster(s, rounded=True) for s in (48, 32, 16)]
    ico[0].save(PUBLIC / "favicon.ico", format="ICO", sizes=[(48, 48), (32, 32), (16, 16)], append_images=ico[1:])

    raster(180, rounded=False).convert("RGB").save(PUBLIC / "apple-touch-icon.png", optimize=True)

    print("wrote public/favicon.svg, public/favicon.ico (16/32/48), public/apple-touch-icon.png (180)")


if __name__ == "__main__":
    main()
