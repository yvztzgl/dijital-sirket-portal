import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { followFlow } from '@core/flow/follow';
import { Assistant } from '@core/services/assistant';
import { ApplicationStore } from '@core/state/application.store';
import { IText, Icon } from '@ui/icon';
import { DemoBar } from '@demo/demo-bar';
import { StepPage } from '@layout/step-page';
import {
  arrivedNumbers,
  BUILDING,
  CONFETTI,
  currentStep,
  doneCount,
  FINISHED_HOLD,
  FLOOR_BANDS,
  mockAgencies,
  mockDetails,
  mockRise,
  serverAgencies,
  serverDetails,
  serverRise,
  subCount,
} from '../../setup-progress.view';

/** D-5a — Şirketiniz kuruluyor. Nothing is asked: a status card with the agency steps and their state. */
@Component({
  selector: 'app-setup-progress-page',
  imports: [DemoBar, IText, Icon, StepPage],
  templateUrl: './setup-progress.html',
  host: { style: 'display:block' },
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class SetupProgressPage {
  protected readonly store = inject(ApplicationStore);
  private readonly assistant = inject(Assistant);
  /** HTTP mode: only the server's steps and tasks, no progress made up by time. */
  protected readonly serverDecides = this.store.serverDecides;

  constructor() {
    this.store.clearError();
    // D-5a stays for a moment after the last step so the finished building is seen, then moves to
    // "Şirketiniz kuruldu" with the "founded" animation (the company's logo travels from the roof sign).
    const founded = (screen: string, stage: string | null) => screen === 'd5a' && stage === 'done';
    followFlow({
      linger: (screen, stage) => (founded(screen, stage) ? FINISHED_HOLD : 0),
      transition: (screen, stage) => (founded(screen, stage) ? 'vt-founded' : null),
    });
  }

  /** HTTP mode: the server's steps; undefined in the mock, null while the server has not created them. */
  private readonly serverSteps = computed(() => this.store.app()?.setup?.steps);

  protected readonly building = BUILDING;
  protected readonly floorBands = FLOOR_BANDS;
  protected readonly confetti = CONFETTI;

  /**
   * D-5a's illustration: a six-storey building, cut open, that rises as the company is founded.
   * The six agency steps that run on this screen (AGENCIES 4 to 9; the first three were finished
   * in earlier steps) are its six floors, from the ground up, and each floor shows a small scene
   * for its step: registry, tax office, financial seal, bank, social security and e-ledger,
   * accountant. The picture (generated by the owner, 2026-11-17) is shown twice: faint and
   * dotted as the plan, and in full up to the height built so far. While a step runs its floor
   * fills in from its own floor line to the slab above it. No step names appear on it.
   * (Before this the owner rejected a drawn "seal sheet", a take-off scene and a plain facade.)
   */
  protected readonly rise = computed(() => (this.serverDecides ? serverRise(this.serverSteps(), this.store.stage()) : mockRise(this.store.setup())));

  /** HTTP mode, stage `setup`, no steps yet: "hazırlanıyor". */
  protected readonly preparing = computed(() => this.serverDecides && this.serverSteps() == null);

  /** "Detayı gör": the full list of steps and sub-steps under the illustration. Open at once in HTTP mode. */
  protected readonly listOpen = signal(this.serverDecides);
  protected readonly detailsOpen = signal(this.serverDecides);

  protected readonly agency = computed(() => (this.serverDecides ? serverAgencies(this.serverSteps()) : mockAgencies(this.store.setup())));
  protected readonly current = computed(() => currentStep(this.store.setup()));
  protected readonly doneCount = computed(() => doneCount(this.store.setup(), this.serverSteps(), this.serverDecides));
  protected readonly subCount = computed(() => subCount(this.store.setup(), this.serverSteps(), this.serverDecides));
  /** Sub-steps of the agencies still running or queued (shown under "Alt adımları göster"). */
  protected readonly details = computed(() => (this.serverDecides ? serverDetails(this.serverSteps()) : mockDetails(this.store.setup())));
  /** HTTP mode: the company's numbers that have arrived so far. */
  protected readonly arrived = computed(() => arrivedNumbers(this.store.app()?.results));

  /** "Belgeleri görüntüle" / "İşlem kaydını görüntüle": open that view in the side panel. */
  protected showPanel(tab: 'docs' | 'log') {
    this.assistant.show(tab);
  }
}
